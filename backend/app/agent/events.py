GOV_MESSAGE_SEQUENCE = [REQUEST_RECEIVED, STATUS_UPDATED]


def make_event(event_type: str, payload: dict | None = None) -> dict:
    return {
        "event_type": event_type,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "payload": payload or {},
    }
